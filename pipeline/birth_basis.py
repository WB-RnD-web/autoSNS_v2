def ipchun(y: int) -> dt.datetime:
    """그 해 입춘 시각(한국 표준시, 시간대 없는 datetime)."""
    md, hm = IPCHUN[y].split()
    return dt.datetime(y, int(md[:2]), int(md[3:]), int(hm[:2]), int(hm[3:]))


def ddi_year(born: dt.date | dt.datetime) -> int:
    """띠를 정하는 해. 입춘 전이면 앞 해. 날짜만 주면 입춘 당일은 새 해로 본다(당일생은 시각에 따라 다르다)."""
    t = ipchun(born.year)
    if isinstance(born, dt.datetime):
        return born.year if born >= t else born.year - 1
    return born.year if born >= t.date() else born.year - 1


def animal_of(year: int) -> str:
    return ANIMALS[(year - 4) % 12]


def odd_days(lo: int, hi: int) -> dict[int, list[int]]:
    """입춘이 2월 4일이 아닌 해 — {5: [1947, …], 3: [2021, …]}."""
    out: dict[int, list[int]] = {}
    for y in range(lo, hi + 1):
        day = ipchun(y).day
        if day != 4:
            out.setdefault(day, []).append(y)
    return out


def _yy(years: list[int]) -> str:
    return "·".join(f"{y % 100:02d}" for y in years) + "년"


def _odd_lines(lo: int, hi: int, what: str) -> list[str]:
    od = odd_days(lo, hi)
    out = []
    if od.get(5):
        out.append(f"· 입춘이 2월 5일인 해({_yy(od[5])})는 2월 4일생도 앞 해 {what}예요.")
    if od.get(3):
        out.append(f"· 입춘이 2월 3일인 해({_yy(od[3])})는 2월 3일 밤에 바뀌어요.")
    return out


