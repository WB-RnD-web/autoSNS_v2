def ipchun(y: int) -> dt.datetime:
    """그 해 입춘 시각(그때 한국 표준시, 시간대 없는 datetime). 표 밖의 해는 ValueError."""
    if y not in IPCHUN:
        raise ValueError(f"입춘 표는 {min(IPCHUN)}~{max(IPCHUN)}년만 있어요: {y}")
    md, hm = IPCHUN[y].split()
    return dt.datetime(y, int(md[:2]), int(md[3:]), int(hm[:2]), int(hm[3:]))


def kst_offset(year: int) -> dt.timedelta:
    """그 해 2월의 한국 표준시 — 1955~1961 은 UTC+8:30(1954-03-21~1961-08-09), 나머지는 UTC+9."""
    return dt.timedelta(hours=8, minutes=30) if 1955 <= year <= 1961 else dt.timedelta(hours=9)


def ddi_year(born: dt.date | dt.datetime) -> int:
    """띠를 정하는 해. 입춘 전이면 앞 해. 날짜만 주면 입춘 당일은 새 해로 본다(당일생은 시각에 따라 다르다).
    시간대 없는 시각은 그때 한국 시각으로 본다. 시간대가 붙은 시각은 그해 한국 표준시(입춘 표와 같은 기준)로 바꿔 본다."""
    if isinstance(born, dt.datetime):
        if born.tzinfo is not None:
            utc = born.astimezone(dt.timezone.utc).replace(tzinfo=None)
            born = utc + kst_offset(utc.year)
        return born.year if born >= ipchun(born.year) else born.year - 1
    return born.year if born >= ipchun(born.year).date() else born.year - 1


def animal_of(year: int) -> str:
    return ANIMALS[(year - 4) % 12]


def odd_days(lo: int, hi: int) -> dict[int, list[int]]:
    """입춘이 2월 4일이 아닌 해 — {5: [1947, …], 3: [2021, …]}."""
    out: dict[int, list[int]] = {}
    for y in range(lo, hi + 1):
        day = ipchun(y).day
        if day != 4:
            out.setdefault(day, []).append(y)
    return out


def _yy(years: list[int]) -> str:
    return "·".join(f"{y % 100:02d}" for y in years) + "년"


def _odd_lines(lo: int, hi: int, what: str) -> list[str]:
    od = odd_days(lo, hi)
    out = []
    if od.get(5):
        out.append(f"· 입춘이 2월 5일인 해({_yy(od[5])})는 2월 4일생도 앞 해 {what}예요.")
    if od.get(3):
        out.append(f"· 입춘이 2월 3일인 해({_yy(od[3])})는 2월 3일 밤에 바뀌어요.")
    return out


